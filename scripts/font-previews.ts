// Run with `bun scripts/font-previews.ts` after changing USERNAME_FONTS.
import opentype from "opentype.js";
import { USERNAME_FONTS } from "../shared/username-fonts";

const SIZE = 48;
const OUT = new URL("../src/ui/font-previews.ts", import.meta.url);

async function fontFile(family: string) {
  const query = family.replaceAll(" ", "+");
  const css = await fetch(`https://api.fonts.coollabs.io/css2?family=${query}`, {
    headers: { "user-agent": "curl" },
  }).then((r) => r.text());
  const url = css.match(/src:\s*url\(([^)]+\.ttf)\)/)?.[1];
  if (!url) throw new Error(`no ttf for ${family}`);
  return fetch(url).then((r) => r.arrayBuffer());
}

const previews: Record<string, { d: string; width: number }> = {};
const tops: number[] = [];
const bottoms: number[] = [];
for (const { id, label, family } of USERNAME_FONTS) {
  if (!family) continue;
  const font = opentype.parse(await fontFile(family));
  const path = font.getPath(label, 0, SIZE, SIZE);
  const box = path.getBoundingBox();
  tops.push(box.y1);
  bottoms.push(box.y2);
  previews[id] = { d: path.toPathData(0), width: Math.ceil(box.x2) };
}

const body = JSON.stringify(previews, null, 2);
await Bun.write(
  OUT,
  `// Generated by scripts/font-previews.ts\nexport const FONT_PREVIEW_TOP = ${Math.floor(Math.min(...tops))};\nexport const FONT_PREVIEW_HEIGHT = ${Math.ceil(Math.max(...bottoms) - Math.floor(Math.min(...tops)))};\nexport const FONT_PREVIEWS: Record<string, { d: string; width: number }> = ${body};\n`
);
console.log(`wrote ${Object.keys(previews).length} previews, ${(body.length / 1024).toFixed(1)} KB`);
